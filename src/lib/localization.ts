type TranslationKey = keyof typeof languages.en
type UiLanguage = keyof typeof languages

const dialectLanguage: Record<SupportedDialect, UiLanguage> = {
  English: 'en',
  Hinglish: 'hi',
  Punjlish: 'pa',
  Tanglish: 'ta',
  Hindi: 'hi',
  Punjabi: 'pa',
  Tamil: 'ta',
  Marathi: 'mr',
}

export function getUiLanguage(dialect: SupportedDialect): UiLanguage {
  return dialectLanguage[dialect]
}

export function getUiLocale(dialect: SupportedDialect): string {
  return { en: 'en-IN', hi: 'hi-IN', pa: 'pa-IN', ta: 'ta-IN', mr: 'mr-IN' }[getUiLanguage(dialect)]
}

export function translate(dialect: SupportedDialect, key: TranslationKey, values?: Record<string, string | number>): string {
  const language = languages[getUiLanguage(dialect)] as Partial<Record<TranslationKey, string>>
  let text: string = language[key] ?? languages.en[key]
  if (values) {
    for (const [name, value] of Object.entries(values)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}
